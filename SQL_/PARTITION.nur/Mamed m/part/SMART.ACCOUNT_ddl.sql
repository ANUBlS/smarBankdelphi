CREATE OR REPLACE TRIGGER after_inc_account
 AFTER
  INSERT
 ON account
REFERENCING NEW AS NEW OLD AS OLD
DECLARE
  I INTEGER;
  nw INTEGER;
  CurrentDate DATE;
	PrevDate DATE;
	
BEGIN
  SELECT tr_seg_account.CURRVAL
    INTO nw
    FROM dual;

  SELECT Tek_dat, Pred_Dat
    INTO CurrentDate, PrevDate
    FROM sysdat;

  sbop.add_archost(nw, CurrentDate);
  sbop.add_archost(nw, PrevDate);
END After_Inc_Account;
/

