DECLARE
 SQLSTR CONSTANT VARCHAR2 (100) := 'REVOKE RESTRICTED SESSION FROM ';
 CURSOR C_USER IS SELECT * FROM USER$ WHERE NAME <>'SMART';
 EXC EXCEPTION ;
 PRAGMA EXCEPTION_INIT (EXC,  -1952);
BEGIN
 FOR USER IN C_USER
 LOOP
 BEGIN
   EXECUTE IMMEDIATE SQLSTR || USER.NAME;
   
   EXCEPTION WHEN EXC THEN
    dbms_output.put_line(' SYSTEM PRIVILEGES NOT GRANTED TO '||''''||USER.NAME||'''');  
 END;   
 END LOOP;
END;
