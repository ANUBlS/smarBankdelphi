CREATE TABLE a2 (a INTEGER, b INTEGER, c VARCHAR(30), d integer)
   PARTITION BY RANGE (a)
   SUBPARTITION BY hash (b)
   SUBPARTITIONS 4
   (
    PARTITION a0 VALUES LESS THAN (1) (SUBPARTITION a0_1, SUBPARTITION a0_2),
    PARTITION a1 VALUES LESS THAN (2) (SUBPARTITION a1_1, SUBPARTITION a1_2),
    PARTITION a2 VALUES LESS THAN (3) (SUBPARTITION a2_1, SUBPARTITION a2_2),
    PARTITION a3 VALUES LESS THAN (4) (SUBPARTITION a3_1, SUBPARTITION a3_2),
    PARTITION a4 VALUES LESS THAN (maxvalue) (SUBPARTITION a4_1, SUBPARTITION a4_2
    ))
/
CREATE Unique INDEX idx_a2_D ON A2(D ASC)
 global PARTITION BY RANGE ( D )
(
 PARTITION p0 VALUES LESS THAN (1)
,PARTITION p1 VALUES LESS THAN (2) 	
,PARTITION p2 VALUES LESS THAN (3) 	
,PARTITION p3 VALUES LESS THAN (4) 	
,PARTITION p4 VALUES LESS THAN (maxvalue) 	
)

