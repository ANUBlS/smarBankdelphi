SELECT
   P.ID 
 , U.NAME as OWNER
 , C.NAME as BOOROWER
 , V.VALU_NAME as CURRENCY
 , P.INITIALAMOUNT 
 , P.CREDITLINEAMOUNT 
 , P.ANNUALYINTERESTRATE 
 , P.ANNUALYOVERDUERATE
 , P.ANNUALYPENALTYRATE 
 , P.DATEOFCONCLUSION 
 , P.DATEOFGRANT 
 , P.DUEDATEFIRSTCONTRACT 
 , P.DUEDATELASTCONTRACT
 , P.CLOSEDATE 
 , P.NUMBEROFCREDIT 
 , P.PURPOSEOFCREDIT 
 , P.CUSTOMERTYPE 
 , T.TYPEDESC  as CREDITTYPE
 , P.USRGROUP 
 , B.NAME as BRANCH
FROM
   CREDITSMGR.CM_PORTFOLIO P
 , SMART.CUSTOMERS C
 , SMART.AVALUTE V
 , CREDITSMGR.CM_BP_TYPES T
 , CREDITSMGR.CM_USERS U
 , SMART.FILIAL B
 , CREDITSMGR.cm_business_plan BP
WHERE
     (C.ID = P.BOOROWERID)
 AND (V.VALUTE = P.CURRENCY)
 AND (U.ID = P.USID)
 AND (B.ID = P.BRANCHID)
 AND (BP.CREDITID = P.ID)
 AND (BP.TYPE = T.ID)
