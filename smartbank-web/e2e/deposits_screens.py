"""Deposits manager (NewDepositsManager) E2E + screenshots (mock mode, fresh API process)."""
import os, sys
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "screenshots")
CHROME = os.getenv("CHROME_PATH", "/usr/bin/google-chrome")
shot = lambda pg, n: (pg.screenshot(path=os.path.join(OUT, n)), print("saved", n))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None, args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1440, "height": 900}, accept_downloads=True)
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE); pg.wait_for_selector("#loginForm")
    pg.fill("#u", "ADMIN"); pg.fill("#p", "Admin#2026"); pg.click("#loginBtn"); pg.wait_for_selector("#tree .node")
    pg.locator("#tree .node", has_text="Deposits").first.click(); pg.wait_for_timeout(200)
    pg.locator("#tree .node", has_text="Deposits").last.click()
    pg.wait_for_selector("#dGrid tbody tr[data-id]"); pg.wait_for_timeout(300)
    rows = pg.locator("#dGrid tbody tr[data-id]")
    expect(rows).to_have_count(8); shot(pg, "242-deposits-main.png")
    pg.click("#dFilter"); pg.wait_for_selector("#dFilterPanel fieldset")
    pg.check("#cb_currency"); pg.wait_for_timeout(400)
    pg.fill("#dD1", "2026-03-01"); pg.dispatch_event("#dD1", "change"); pg.fill("#dD2", "2026-10-20"); pg.dispatch_event("#dD2", "change")
    pg.check("#cb_opendat"); pg.wait_for_timeout(400)
    pg.locator("#dGrid th[data-f='AMOUNT']").click(); pg.wait_for_timeout(300); pg.locator("#dGrid th[data-f='AMOUNT']").click(); pg.wait_for_timeout(400)
    expect(rows).to_have_count(4); assert rows.first.get_attribute("data-id") == "5003"; shot(pg, "243-deposits-filter.png")
    with pg.expect_download() as dl: pg.click("#dExp")
    assert dl.value.suggested_filename.endswith(".xlsx")
    pg.uncheck("#cb_currency"); pg.uncheck("#cb_opendat"); pg.wait_for_timeout(400); pg.click("#dFilter")
    pg.locator("#dGrid tr[data-id='5002']").click(button="right"); pg.wait_for_selector(".ctx-menu")
    pg.locator(".ctx-menu .ctx-item", has_text=pg.evaluate("SB.t('deposits.m_contract')")).first.hover(); pg.wait_for_timeout(200); shot(pg, "244-deposits-popup.png")
    pg.keyboard.press("Escape")
    pg.click("#dOps"); pg.wait_for_selector(".ctx-menu"); shot(pg, "245-deposits-operations.png"); pg.keyboard.press("Escape")
    pg.click("#dSett"); pg.wait_for_selector(".ctx-menu"); pg.locator(".ctx-menu .ctx-item.sub").first.hover(); pg.wait_for_timeout(200); shot(pg, "246-deposits-settings.png"); pg.keyboard.press("Escape")
    pg.locator("#dGrid tr[data-id='5001']").click(); pg.keyboard.press("Control+Shift+S"); pg.wait_for_selector("#dSearch input")
    pg.fill("#dSearch input[data-sf='CUSTOMERNAME']", "məm"); pg.press("#dSearch input[data-sf='CUSTOMERNAME']", "Enter"); pg.wait_for_timeout(300)
    shot(pg, "247-deposits-search.png")
    pg.locator("#dGrid tr[data-id='5002']").click(); pg.keyboard.press("F8"); pg.wait_for_timeout(600)
    expect(rows).to_have_count(7); shot(pg, "248-deposits-closed.png")
    pg.locator("#dGrid tr[data-id='5001']").dblclick(); pg.wait_for_selector(".toast"); shot(pg, "249-deposits-not-migrated.png")
    b.close()
