"""Accounts re-audit E2E + screenshots (mock mode): left filter sidebar, Delphi columns/formats, filters, search, popup, child forms."""
import os, sys
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "screenshots")
CHROME = os.getenv("CHROME_PATH", "/usr/bin/google-chrome")
shot = lambda pg, n: (pg.screenshot(path=os.path.join(OUT, n)), print("saved", n))
rows = lambda pg: pg.locator("#accGrid tbody tr")
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None, args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1500, "height": 900})
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE); pg.wait_for_selector("#loginForm")
    pg.fill("#u", "ADMIN"); pg.fill("#p", "Admin#2026"); pg.click("#loginBtn"); pg.wait_for_selector("#tree .node")
    pg.evaluate("localStorage.removeItem('sb.flt.ADMIN.accounts')")
    pg.locator("#tree .node", has_text="Accounts").first.click()
    pg.locator("#tree .node", has_text="Accounts").nth(1).click()
    pg.wait_for_selector("#accGrid tbody tr"); pg.wait_for_timeout(300)
    expect(rows(pg)).to_have_count(8)                                  # Delphi default: ApplyFilter + active accounts
    expect(pg.locator("#accGrid thead")).to_contain_text("Planned balance")
    expect(pg.locator("#accGrid tbody")).to_contain_text("1 234 567,89")
    shot(pg, "190-accounts-sidebar-default.png")
    pg.check(".flt-body [name=status][value=all]"); pg.check(".flt-body [name=use_fil]"); pg.select_option(".flt-body [name=filial_id]", "102")
    pg.click("[data-flt-apply]"); pg.wait_for_timeout(400); expect(rows(pg)).to_have_count(3)
    pg.check(".flt-body [name=use_flag]"); pg.select_option(".flt-body [name=flag]", "I"); pg.click("[data-flt-apply]"); pg.wait_for_timeout(400)
    expect(rows(pg)).to_have_count(1); shot(pg, "191-accounts-filter-branch-flag.png")
    pg.click("[data-flt-clear]"); pg.wait_for_timeout(500); expect(rows(pg)).to_have_count(8)
    pg.check(".flt-body [name=use_cust]"); pg.fill(".flt-body [name=cust_code]", "3"); pg.check(".flt-body [name=use_cur]"); pg.select_option(".flt-body [name=currency_id]", "978")
    pg.click("[data-flt-apply]"); pg.wait_for_timeout(400); expect(rows(pg)).to_have_count(1); shot(pg, "192-accounts-filter-customer-currency.png")
    pg.click("[data-flt-clear]"); pg.wait_for_timeout(500)
    pg.fill(".flt-body [data-find=accname]", "Caspian"); pg.press(".flt-body [data-find=accname]", "Enter"); pg.wait_for_timeout(200)
    expect(pg.locator("#accGrid tr.sel")).to_contain_text("Caspian Trade LLC")
    pg.fill(".flt-body [data-find=accname]", "Nobody"); pg.press(".flt-body [data-find=accname]", "Enter"); pg.wait_for_timeout(200)
    expect(pg.locator("#accFindHint")).to_contain_text("Account not found"); shot(pg, "193-accounts-search.png")
    pg.locator("#accGrid tr", has_text="AZ12SMRT33010097800000000008").click(button="right"); pg.wait_for_selector(".ctx-menu")
    pg.hover(".ctx-item.sub"); pg.wait_for_timeout(200); shot(pg, "194-accounts-popup-menu.png"); pg.keyboard.press("Escape")
    pg.locator("#accGrid tr", has_text="AZ12SMRT33010097800000000008").dblclick(); pg.wait_for_selector("#af")
    expect(pg.locator("#af [name=pair_q]")).to_have_value("AZ12SMRT33010084000000000006"); expect(pg.locator("#flagsTxt")).to_have_text("I")
    pg.wait_for_timeout(200); shot(pg, "195-account-edit-codes-flags.png")
    pg.click("#flagsBtn"); pg.wait_for_timeout(200); shot(pg, "196-account-flags-dialog.png"); pg.keyboard.press("Escape")
    pg.click("#acancel"); pg.wait_for_timeout(200)
    pg.locator("#accGrid tr", has_text="AZ12SMRT30010084000000000010").click(); pg.click("[data-a=tr]"); pg.wait_for_selector("#dok")
    shot(pg, "197-account-dates-dialog.png"); pg.click("#dok"); pg.wait_for_selector("#tdest"); pg.wait_for_timeout(300)
    expect(pg.locator(".modal thead")).to_contain_text("D.Amount"); expect(pg.locator("#tdest")).to_have_value("Nostro funding")
    shot(pg, "198-account-transactions-delphi-columns.png"); pg.click("#tok")
    pg.click("[data-a=states]"); pg.wait_for_selector("[data-pg=turnovers]"); pg.click("[data-pg=turnovers]"); pg.wait_for_timeout(200)
    shot(pg, "199-account-states-turnovers.png"); pg.click("#sok")
    pg.click(".flt-toggle"); pg.wait_for_timeout(300); shot(pg, "200-accounts-sidebar-collapsed.png")
    pg.reload(); pg.wait_for_selector("#tree .node"); pg.wait_for_timeout(1500)
    if pg.locator("#accGrid tbody tr").count() == 0:
        pg.locator("#tree .node", has_text="Accounts").first.click(); pg.locator("#tree .node", has_text="Accounts").nth(1).click()
    pg.wait_for_selector("#accGrid tbody tr"); assert pg.locator(".flt-layout.collapsed").count() == 1   # remembered per user
    pg.click(".flt-toggle")
    pg.set_viewport_size({"width": 760, "height": 1000}); pg.wait_for_timeout(400); shot(pg, "201-accounts-sidebar-narrow.png")
    b.close()
print("ACCOUNTS PARITY E2E OK")
