"""Accounts module E2E + screenshots (mock mode)."""
import os, sys
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "screenshots")
CHROME = os.getenv("CHROME_PATH", "/usr/bin/google-chrome")
shot = lambda pg, n: (pg.screenshot(path=os.path.join(OUT, n)), print("saved", n))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None, args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1440, "height": 860})
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE); pg.wait_for_selector("#loginForm")
    pg.fill("#u", "ADMIN"); pg.fill("#p", "Admin#2026"); pg.click("#loginBtn"); pg.wait_for_selector("#tree .node")
    pg.locator("#tree .node", has_text="Accounts").first.click()
    pg.locator("#tree .node", has_text="Accounts").nth(1).click()
    pg.wait_for_selector(".acc-grid tbody tr"); pg.wait_for_timeout(300); shot(pg, "20-accounts-list.png")
    pg.click("[data-a=filter]"); pg.check("[name=apply_filter]"); pg.check("[name=status][value=active]")
    pg.check("[name=use_cust]"); pg.select_option("[name=customer_id]", "3"); pg.click("#accFilter .btn")
    pg.wait_for_timeout(400); expect(pg.locator(".acc-grid tbody tr")).to_have_count(2); shot(pg, "21-accounts-filter.png")
    pg.click("[data-a=new]"); pg.wait_for_selector("#af"); pg.fill("[name=acc_no]", "AZ12SMRT3801*0019440000000123")
    pg.click("#asave"); pg.wait_for_selector("#aerr .alert"); expect(pg.locator("#aerr")).to_contain_text("Currency"); shot(pg, "22-account-new-validation.png")
    pg.select_option("#af [name=currency_id]", "944"); pg.select_option("#af [name=sacc]", "3801"); pg.select_option("#af [name=customer_id]", "2")
    expect(pg.locator("#af [name=acc_name]")).to_have_value("Kamran Aliyev")
    pg.check("#af [name=flag] >> nth=1"); pg.click("#asave"); pg.wait_for_timeout(600)
    expect(pg.locator("#modal-root")).to_be_empty()
    pg.uncheck("[name=apply_filter]"); pg.click("#accFilter .btn"); pg.wait_for_timeout(400)
    expect(pg.locator(".acc-grid tbody tr")).to_have_count(8)
    pg.locator(".acc-grid tr", has_text="AZ12SMRT38010019440000000001").click(); pg.click("[data-a=edit]")
    pg.wait_for_selector("#af"); pg.wait_for_timeout(300); shot(pg, "23-account-edit.png"); pg.keyboard.press("Escape")
    pg.click("[data-a=close]"); pg.wait_for_timeout(300); shot(pg, "24-account-close-balance.png")
    pg.click("[data-a=tr]"); pg.wait_for_selector(".tabs"); pg.wait_for_timeout(300); shot(pg, "25-account-transactions.png")
    pg.click("#tok"); pg.click("[data-a=states]"); pg.wait_for_selector(".modal table"); shot(pg, "26-account-states.png")
    b.close()
print("ACCOUNTS E2E OK")
