"""Deposits: Yatırım (NewDepositsApplyMoney) and Əmanətin ödənilməsi (NewDepositsExtractMoney) E2E + screenshots 255-259."""
import os, sys
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "screenshots")
CHROME = os.getenv("CHROME_PATH", "/usr/bin/google-chrome")
shot = lambda pg, n: (pg.screenshot(path=os.path.join(OUT, n)), print("saved", n))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None, args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE); pg.wait_for_selector("#loginForm")
    pg.fill("#u", "ADMIN"); pg.fill("#p", "Admin#2026"); pg.click("#loginBtn"); pg.wait_for_selector("#tree .node")
    pg.locator("#tree .node", has_text="Deposits").first.click(); pg.wait_for_timeout(200)
    pg.locator("#tree .node", has_text="Deposits").last.click(); pg.wait_for_selector("#dGrid tbody tr[data-id]")
    pg.locator("#dGrid tr[data-id='5001']").click(); pg.keyboard.press("Control+d"); pg.wait_for_selector("#amNew")
    shot(pg, "255-deposits-apply-list.png")
    pg.click("#amNew"); pg.wait_for_selector("#amSum"); pg.fill("#amSum", "500"); pg.select_option("#amAcc", "930001"); pg.wait_for_timeout(400)
    shot(pg, "256-deposits-apply-add.png")
    pg.click("#amOk"); pg.wait_for_selector("#ttOk"); shot(pg, "257-deposits-delayed-confirm.png")
    pg.click("#ttOk"); pg.wait_for_timeout(600)
    expect(pg.locator("#amBody tr[data-id]")).to_have_count(2)
    pg.click("#amExit"); pg.wait_for_timeout(400)
    pg.locator("#dGrid tr[data-id='5003']").click(); pg.keyboard.press("Control+m"); pg.wait_for_selector("#emNew")
    shot(pg, "258-deposits-extract-list.png")
    pg.click("#emNew"); pg.wait_for_selector("#emMain"); pg.fill("#emMain", "1000"); pg.fill("#emInt", "100"); pg.fill("#emClient", "0")
    shot(pg, "259-deposits-extract-add.png")
    pg.click("#emOk"); pg.wait_for_selector("#ttOk"); pg.click("#ttOk"); pg.wait_for_timeout(600)
    expect(pg.locator("#emBody tr[data-id]")).to_have_count(2)
    b.close()
