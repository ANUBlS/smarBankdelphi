"""Transaction manager re-audit E2E + screenshots (mock mode): left 'Seçimlər' sidebar, Delphi columns/formats, each filter, search, popup, child forms."""
import os, sys
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "screenshots")
CHROME = os.getenv("CHROME_PATH", "/usr/bin/google-chrome")
shot = lambda pg, n: (pg.screenshot(path=os.path.join(OUT, n)), print("saved", n))
rows = lambda pg: pg.locator("#trGrid tbody tr[data-id]")
def wait(pg, n): pg.wait_for_timeout(350); expect(rows(pg)).to_have_count(n)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None, args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1600, "height": 950})
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE); pg.wait_for_selector("#loginForm")
    pg.fill("#u", "TELLER"); pg.fill("#p", "Teller#2026"); pg.click("#loginBtn"); pg.wait_for_selector("#tree .node")
    pg.evaluate("localStorage.removeItem('sb.flt.TELLER.transactionmanager')")
    pg.locator("#tree .node", has_text="Transactions").first.click()
    pg.locator("#tree .node", has_text="Transaction manager").first.click()
    pg.wait_for_selector("#trGrid tbody tr[data-id]"); wait(pg, 10)
    expect(pg.locator("#trGrid thead")).to_contain_text("№"); expect(pg.locator("#trGrid thead")).to_contain_text("Entered by")
    expect(pg.locator("#trGrid tbody")).to_contain_text("9 999,00"); expect(pg.locator("#sysDate")).not_to_be_empty()
    shot(pg, "202-tm-sidebar-default.png")
    pg.locator(".flt-body [data-cur='978']").uncheck(); wait(pg, 9)
    pg.locator(".flt-body [data-cur='840']").uncheck(); wait(pg, 6); shot(pg, "203-tm-filter-currency.png")
    pg.click("[data-flt-clear]"); wait(pg, 10)
    pg.check(".flt-body #use_db"); pg.select_option(".flt-body #selDb", "102"); wait(pg, 1)
    pg.uncheck(".flt-body #use_db"); wait(pg, 10)
    pg.check(".flt-body #use_cb"); pg.select_option(".flt-body #selCb", "102"); pg.wait_for_timeout(350)
    assert 0 < rows(pg).count() < 10; shot(pg, "204-tm-filter-credit-branch.png")
    pg.click("[data-flt-clear]"); wait(pg, 10)
    pg.check(".flt-body #use_op"); pg.wait_for_timeout(350); assert 0 < rows(pg).count() < 10
    pg.locator(".flt-body [data-op='2']").uncheck(); pg.wait_for_timeout(350)
    pg.locator(".flt-body [data-st=rejected]").uncheck(); pg.wait_for_timeout(350); shot(pg, "205-tm-filter-user-optype-kind.png")
    pg.click("[data-flt-clear]"); wait(pg, 10)
    pg.fill(".flt-body [data-ss=debitamount]", "1500"); pg.press(".flt-body [data-ss=debitamount]", "Enter")
    pg.wait_for_selector("#qy"); pg.click("#qy"); pg.wait_for_timeout(250)   # cursor starts on the last row -> "search from the beginning?"
    expect(pg.locator("#trGrid tr.sel")).to_contain_text("1 500,00")
    expect(pg.locator("#trDetail")).to_contain_text("Operation purpose:"); shot(pg, "206-tm-search-detail.png")
    pg.locator("#trGrid tr[data-id='6006']").click(button="right"); pg.wait_for_selector(".ctx-menu"); pg.wait_for_timeout(150)
    shot(pg, "207-tm-popup-menu.png"); pg.keyboard.press("Escape")
    pg.click("[data-a=refmenu]"); pg.wait_for_selector(".ctx-menu"); pg.wait_for_timeout(150); shot(pg, "208-tm-refresh-dropdown.png")
    pg.locator(".ctx-item", has_text="Full refresh").click(); wait(pg, 10)
    pg.click("[data-a=commission]"); pg.wait_for_selector("#cadd"); pg.locator(".modal tr[data-i]", has_text="komissiya ilə").click(); pg.wait_for_timeout(150)
    expect(pg.locator(".modal thead")).to_contain_text("Commission debit"); shot(pg, "209-tm-commission-list.png")
    pg.click("#cc"); pg.wait_for_timeout(300)
    pg.locator("#trGrid tr[data-id='6006']").dblclick(); pg.wait_for_selector("#tf"); pg.wait_for_timeout(500)
    expect(pg.locator("#tf [data-code-for=debit_currency_id]")).to_have_value("978"); expect(pg.locator("#tf [data-code-for=operation_code]")).to_have_value("1")
    shot(pg, "210-tm-editor-code-edits.png")
    pg.locator("#tf [name=name]").press("F3"); pg.wait_for_selector("#dok"); pg.wait_for_timeout(150); shot(pg, "211-tm-destination-picker.png")
    pg.click("#dc"); pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    pg.locator("#trGrid").click(position={"x": 5, "y": 5}); pg.keyboard.press("Alt+f"); pg.wait_for_timeout(300)
    assert pg.locator(".flt-layout.collapsed").count() == 1; shot(pg, "212-tm-sidebar-collapsed.png")
    pg.keyboard.press("Alt+f"); pg.wait_for_timeout(200)
    pg.set_viewport_size({"width": 760, "height": 1100}); pg.wait_for_timeout(400); shot(pg, "213-tm-sidebar-narrow.png")
    b.close()
print("TM PARITY E2E OK")
