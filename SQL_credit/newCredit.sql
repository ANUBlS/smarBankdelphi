SELECT
   B.NUMBEROFCREDIT as "Muq Nomresi"
 , B.DATEOFCONCLUSION as "ACILMA TARIXI"
 , B.DUEDATEFIRSTCONTRACT as "Baglanma Tarixi"
 , CM_UTILS.BankDaysBetween(B.DATEOFCONCLUSION,B.DUEDATEFIRSTCONTRACT) as "Muddet Gunle"
 , CM_COMMON.AccountNumber_Get(A.LOANACCID) as "SSUDA HESABI"
 , CREDITSMGR.CM_COMMON.AccountNumber_Get(A.DUELOANACCID) as "GECIKMISH SSUDA HESABI" 
 , T.PERCENT as "Ehtiyyat Faizi" 
 , J.VAL_NAME as "VALYUTA"
 , L.NAME as "MUSHTERI"  
 , C.REST as "Esas Borc"
 , C.DUEREST as "Gecikmish Borc"
 , C.REST + C.DUEREST as "Cemi"
 
 , C.REST * O.OSTAT as "Manat Esas Borc"
 , C.DUEREST * O.OSTAT as "Manat Gecikmish Borc"
 , C.REST * O.OSTAT + C.DUEREST * O.OSTAT as "Manat Cemi"
 
 , C.INTERESTREST as "ESAS BORC UZRE FAIZ"
 , C.DUEINTERESTREST as "Geciken Borc uzre faiz"
FROM
   CREDITSMGR.CM_ACCOUNTS A
 , CREDITSMGR.CM_HISTORY C
 , CREDITSMGR.CM_PORTFOLIO B
 , CREDITSMGR.CM_GUARANTEE G
 , CREDITSMGR.SB_AVALUTE J
 , CREDITSMGR.CM_BOOROWERINFO L
 , CREDITSMGR.SB_OPERKURS O
 , CREDITSMGR.CM_RESERVE_TYPES T  
WHERE
     (B.ID = A.CREDITID)
 AND (C.CREDITID = B.ID)
 AND (G.CREDITID = B.ID)
 AND (J.VALUTE = B.CURRENCY)
 AND (L.CREDITID = B.ID)
 AND (C.HDATE = '31-JAN-2005')
 AND (O.VAL_KOD = B.CURRENCY)
 AND (O.DAT='31-JAN-2005')
 AND (T.ID=C.RESERVEID)
