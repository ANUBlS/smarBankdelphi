SELECT * 
FROM CM_BOOROWERINFO
WHERE 

((BOOROWERID IS NOT NULL) AND (NAME IS NULL)) OR 
((BOOROWERID IS NULL) AND (NAME IS NOT NULL)) OR 

((FIRSTOWNERID IS NOT NULL) AND (FIRSTOWNERNAME IS NULL)) OR 
((FIRSTOWNERID IS NULL) AND (FIRSTOWNERNAME IS NOT NULL)) OR 

((SECONDOWNERID IS NOT NULL) AND (SECONDOWNERNAME IS NULL)) OR 
((SECONDOWNERID IS NULL) AND (SECONDOWNERNAME IS NOT NULL)) OR 

((THIRDOWNERID IS NOT NULL) AND (THIRDOWNERNAME IS NULL)) OR 
((THIRDOWNERID IS NULL) AND (THIRDOWNERNAME IS NOT NULL)) 

